CREATE TABLE TIMESHEET_DAILY (
  timesheet_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  period_id NUMBER NOT NULL,
  employee_id NUMBER NOT NULL,
  work_date DATE NOT NULL,
  employee_shift_id NUMBER,
  first_in TIMESTAMP,
  last_out TIMESTAMP,
  worked_minutes NUMBER(5) DEFAULT 0 NOT NULL,
  paid_leave_minutes NUMBER(5) DEFAULT 0 NOT NULL,
  paid_holiday_minutes NUMBER(5) DEFAULT 0 NOT NULL,
  paid_minutes NUMBER(5) DEFAULT 0 NOT NULL,
  late_minutes NUMBER(5) DEFAULT 0 NOT NULL,
  status VARCHAR2(20 CHAR) DEFAULT 'ERROR' NOT NULL,
  error_message VARCHAR2(500 CHAR),
  row_version NUMBER(10) DEFAULT 1 NOT NULL,
  CONSTRAINT uq_17_01 UNIQUE (employee_id,work_date),
  CONSTRAINT ck_17_01 CHECK (work_date = TRUNC(work_date)),
  CONSTRAINT ck_17_02 CHECK (worked_minutes >= 0 AND paid_leave_minutes >= 0 AND paid_holiday_minutes >= 0 AND paid_minutes BETWEEN 0 AND 1440 AND late_minutes >= 0),
  CONSTRAINT ck_17_03 CHECK (paid_minutes = worked_minutes + paid_leave_minutes + paid_holiday_minutes),
  CONSTRAINT ck_17_04 CHECK (status IN ('VALID','ERROR')),
  CONSTRAINT ck_17_05 CHECK (last_out IS NULL OR first_in IS NULL OR last_out >= first_in)

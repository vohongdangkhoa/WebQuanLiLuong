-- Tài khoản ứng dụng; API quản lý hash mật khẩu và xác thực
CREATE TABLE APP_USER (
  user_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  username VARCHAR2(100 CHAR) NOT NULL,
  password_hash VARCHAR2(500 CHAR) NOT NULL,
  employee_id NUMBER,
  is_active CHAR(1) DEFAULT 'Y' NOT NULL,
  security_version NUMBER(10) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_01_01 UNIQUE (username),
  CONSTRAINT uq_01_02 UNIQUE (employee_id),
  CONSTRAINT ck_01_01 CHECK (is_active IN ('Y','N')),
  CONSTRAINT ck_01_02 CHECK (username = LOWER(TRIM(username))),
  CONSTRAINT ck_01_03 CHECK (security_version >= 1)
);
COMMENT ON TABLE APP_USER IS 'Tài khoản ứng dụng; API quản lý hash mật khẩu và xác thực';
COMMENT ON COLUMN APP_USER.user_id IS 'Khóa tài khoản';
COMMENT ON COLUMN APP_USER.username IS 'Tên đăng nhập chuẩn hóa chữ thường';

-- Run as SYSTEM connected to FREEPDB1, not CDB$ROOT.
-- SQL*Plus prompts hide passwords. No DROP USER is included.
SET SERVEROUTPUT ON;
SET DEFINE ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
DECLARE
BEGIN
  IF SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20001,'Connect SYSTEM to FREEPDB1 first');
  END IF;
END;
/
ACCEPT owner_password CHAR PROMPT 'New PAYROLL_APP password: ' HIDE
CREATE USER PAYROLL_APP IDENTIFIED BY "&owner_password" DEFAULT TABLESPACE USERS QUOTA 200M ON USERS;
UNDEFINE owner_password
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER, CREATE SEQUENCE TO PAYROLL_APP;
ACCEPT api_password CHAR PROMPT 'New PAYROLL_API password: ' HIDE
CREATE USER PAYROLL_API IDENTIFIED BY "&api_password";
UNDEFINE api_password
GRANT CREATE SESSION TO PAYROLL_API;
